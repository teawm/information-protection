# ===================================================================
# Генерация безопасного простого числа P = 2Q + 1
# ===================================================================
def generate_safe_prime(bits):
    """
    Генерирует безопасное простое число P = 2Q + 1,
    где Q - простое число Софи Жермен.

    Алгоритм:
    1. Генерация случайное простое Q заданной битовой длины
    2. P = 2Q + 1
    3. Проверка P на простоту
    4. Повторение, пока не будет удовлетворять условию
    """
    while True:
        Q = generate_prime(bits)
        P = 2 * Q + 1
        if Ferma_test(P, k=20):
            return P, Q

# ===================================================================
# Генерация первообразного корня g для безопасного простого P
# ===================================================================
def generate_primitive_root(P, Q):
    """
    Генерирует первообразный корень g по модулю P = 2Q + 1.

    Если P = 2Q + 1 - безопасное простое,
    то первообразным корнем будет любое g, для которого:
        2 <= g < P - 1  и  g^Q mod P != 1
    """
    g = 2
    while g < P - 1:
        # Проверяем: g^Q mod P != 1
        if fast_pow_mod(g, Q, P) != 1:
            return g
        g += 1

    raise ValueError(f"Не удалось найти первообразный корень для P={P}")

# ===================================================================
# Схема Диффи-Хеллмана - построение общего ключа
# ===================================================================
def diffie_hellman(P, g, X_A, X_B):
    """
    Реализует схему Диффи-Хеллмана согласно условию.

    ВХОД:
        P    - безопасное простое число (P = 2Q + 1)
        g    - первообразный корень по модулю P
        X_A  - закрытый ключ А (1 <= X_A < P)
        X_B  - закрытый ключ Б   (1 <= X_B < P)

    ВЫХОД:
        (Y_A, Y_B, Z_AB, Z_BA) - открытые ключи и общие секреты

    Алгоритм:
        1. Y_A = g^{X_A} mod P  (открытый ключ А)
        2. Y_B = g^{X_B} mod P  (открытый ключ Б)
        3. Z_AB = Y_B^{X_A} mod P  (секрет А)
        4. Z_BA = Y_A^{X_B} mod P  (секрет Б)
        5. Z_AB = Z_BA = g^{X_A * X_B} mod P
    """
    # Открытые ключи
    Y_A = fast_pow_mod(g, X_A, P)
    Y_B = fast_pow_mod(g, X_B, P)

    # Общие секретные ключи
    Z_AB = fast_pow_mod(Y_B, X_A, P)
    Z_BA = fast_pow_mod(Y_A, X_B, P)

    return Y_A, Y_B, Z_AB, Z_BA

# ===================================================================
# Генерация параметров для схемы Диффи-Хеллмана
# ===================================================================
def generate_diffie_hellman_parameters(bits):
    """
    Генерирует все параметры системы:
    - P, Q - безопасное простое и число Софи Жермен
    - g    - первообразный корень по модулю P
    - X_A, X_B - закрытые ключи А и Б
    """
    P, Q = generate_safe_prime(bits)
    g = generate_primitive_root(P, Q)

    # Закрытые ключи: 1 <= X_i < P
    X_A = random.randint(1, P - 1)
    X_B = random.randint(1, P - 1)

    return P, Q, g, X_A, X_B

